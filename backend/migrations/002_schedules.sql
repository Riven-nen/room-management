-- 002_schedules.sql
-- Semester schedule, master schedule, and registration invite codes.

-- ---------------------------------------------------------------------------
-- Semesters
-- ---------------------------------------------------------------------------
create table if not exists semesters (
    id bigint generated by default as identity primary key,
    school_year text not null,
    term text not null check (term in ('1st Semester', '2nd Semester', 'Summer')),
    is_active boolean not null default false,
    created_by bigint references users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (school_year, term)
);

-- Only one semester can be the active/default one at a time.
create unique index if not exists semesters_one_active_idx
    on semesters ((is_active)) where is_active;

-- ---------------------------------------------------------------------------
-- Semester-based class schedule
-- ---------------------------------------------------------------------------
create table if not exists semester_schedules (
    id bigint generated by default as identity primary key,
    semester_id bigint not null references semesters(id) on delete cascade,
    course text not null,
    year_level text not null,
    section text not null,
    subject_code text,
    subject text not null,
    instructor text,
    day_of_week smallint not null check (day_of_week between 1 and 7),
    start_time time not null,
    end_time time not null,
    room text,
    created_by bigint references users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (end_time > start_time)
);

create index if not exists semester_schedules_semester_idx
    on semester_schedules (semester_id);
create index if not exists semester_schedules_filter_idx
    on semester_schedules (semester_id, course, year_level, section);
create index if not exists semester_schedules_day_idx
    on semester_schedules (semester_id, day_of_week, start_time);

-- ---------------------------------------------------------------------------
-- Master schedule (university-wide calendar)
-- ---------------------------------------------------------------------------
create table if not exists master_schedule_events (
    id bigint generated by default as identity primary key,
    title text not null,
    description text,
    event_type text not null default 'event'
        check (event_type in ('event', 'holiday', 'exam', 'enrollment', 'deadline', 'other')),
    starts_on date not null,
    ends_on date,
    all_day boolean not null default true,
    start_time time,
    end_time time,
    location text,
    created_by bigint references users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (ends_on is null or ends_on >= starts_on),
    check (all_day or start_time is not null)
);

create index if not exists master_schedule_events_dates_idx
    on master_schedule_events (starts_on, ends_on);

-- ---------------------------------------------------------------------------
-- Invite codes (MIS staff / admin / faculty registration)
-- ---------------------------------------------------------------------------
create table if not exists invite_codes (
    id bigint generated by default as identity primary key,
    role user_role not null check (role in ('faculty', 'admin', 'mis_staff')),
    code_hash text not null,
    label text,
    max_uses integer not null default 1 check (max_uses > 0),
    uses integer not null default 0 check (uses >= 0),
    expires_at timestamptz,
    revoked_at timestamptz,
    created_by bigint references users(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists invite_codes_role_idx on invite_codes (role);

-- Keep the same security posture as the existing tables: RLS on, and the
-- Express API (which connects as the postgres owner) is the only writer.
alter table semesters enable row level security;
alter table semester_schedules enable row level security;
alter table master_schedule_events enable row level security;
alter table invite_codes enable row level security;
