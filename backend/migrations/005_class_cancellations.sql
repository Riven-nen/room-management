-- 005_class_cancellations.sql
-- Link schedule entries to faculty accounts and allow one-date class cancellations.
-- A cancellation frees that room/time for booking on that date only.

alter table semester_schedules
    add column if not exists instructor_id bigint references users(id) on delete set null;

update semester_schedules ss
set instructor_id = u.id
from users u
where ss.instructor_id is null
  and u.role = 'faculty'
  and lower(trim(ss.instructor)) = lower(u.name);

create index if not exists semester_schedules_instructor_idx
    on semester_schedules (instructor_id);

create table if not exists class_cancellations (
    id bigint generated by default as identity primary key,
    schedule_id bigint not null references semester_schedules(id) on delete cascade,
    cancelled_on date not null,
    reason text,
    cancelled_by bigint references users(id) on delete set null,
    created_at timestamptz not null default now(),
    unique (schedule_id, cancelled_on)
);

create index if not exists class_cancellations_schedule_date_idx
    on class_cancellations (schedule_id, cancelled_on);

alter table class_cancellations enable row level security;
